#include <eru/eru.h>

unsigned char code[] = { // Bytes from `code.s`
  0x48, 0x65, 0x6c, 0x6c, 0x6f, 0x2c, 0x20, 0x77, 0x6f, 0x72, 0x6c, 0x64,
  0x21, 0x0a, 0xb8, 0x01, 0x00, 0x00, 0x00, 0xbf, 0x01, 0x00, 0x00, 0x00,
  0x48, 0x8d, 0x35, 0xe1, 0xff, 0xff, 0xff, 0xba, 0x0e, 0x00, 0x00, 0x00,
  0x0f, 0x05, 0xb8, 0x3c, 0x00, 0x00, 0x00, 0xbf, 0x00, 0x00, 0x00, 0x00,
  0x0f, 0x05
};
unsigned int code_len = 50;

int main(void)
{
	beginElf();
	elfSetBaseAddr(0x42000);
	elfSetType(ET_EXEC);
	elfSetMachine(EM_X86_64);
	elfSetData(ELFDATA2LSB);

	beginPhdr();
	phdrSetType(PT_LOAD);
	phdrSetFlags(PF_R | PF_X);
	phdrSetAlign(0x1000);
	phdrSetData(code, code_len);

	elfSetEntry(phdrGetOffset(14));
	endPhdr();

	Elf *elf = endElf();
	writeToFile(elf, "basic.out");
	freeElf(elf);
}
